    [Fact]
    public void OrderBy_AudioWithAutoGeneratedSortNames_SortsAlphabeticallyByTitleNotByTrackNumber()
    {
        // The regression this branch exists for: track order is baked into the auto SortName,
        // so honouring it would make "Name Ascending" produce track order instead of A-Z.
        var items = new BaseItem[]
        {
            NewAudio("Zebra", "0001 - Zebra"),
            NewAudio("Apple", "0002 - Apple"),
            NewAudio("Mango", "0003 - Mango"),
        };

        Assert.Equal(["Apple", "Mango", "Zebra"], NamesOf(new NameOrder().OrderBy(items)));
        Assert.Equal(["Zebra", "Mango", "Apple"], NamesOf(new NameOrderDesc().OrderBy(items)));
    }

    [Fact]
    public void OrderBy_ManualSortName_OverridesName()
    {
        var items = new BaseItem[]
        {
            NewAudio("Apple", "zz sorted last"),
            NewAudio("Zebra", "aa sorted first"),
        };

        Assert.Equal(["Zebra", "Apple"], NamesOf(new NameOrder().OrderBy(items)));
        Assert.Equal(["Apple", "Zebra"], NamesOf(new NameOrderDesc().OrderBy(items)));
    }

    [Fact]
    public void OrderBy_UsesNaturalComparer_NumbersNumericallyAndFirst_AndIsCaseInsensitive()
    {
        // SharedNaturalComparer: leading numbers compare numerically, strings that start with
        // a number sort before strings that do not, and the tail compares OrdinalIgnoreCase
        // (so lowercase "apple" precedes "Banana" - plain ordinal would invert that).
        var items = new BaseItem[]
        {
            NewMovie("Banana", "Banana"),
            NewMovie("10 Things", "10 Things"),
            NewMovie("apple", "apple"),
            NewMovie("2 Fast", "2 Fast"),
        };

        Assert.Equal(["2 Fast", "10 Things", "apple", "Banana"], NamesOf(new NameOrder().OrderBy(items)));
    }

    [Fact]
    public void OrderBy_Descending_KeepsInputOrderAmongEqualKeys()
    {
        // Descending is OrderByDescending on the same key, NOT a reversal of the ascending
        // result - so ties keep their incoming order in both directions.
        var first = NewMovie("Alpha", "same key");
        var second = NewMovie("Beta", "same key");
        var items = new BaseItem[] { first, second };

        Assert.Equal(["Alpha", "Beta"], NamesOf(new NameOrder().OrderBy(items)));
        Assert.Equal(["Alpha", "Beta"], NamesOf(new NameOrderDesc().OrderBy(items)));
    }

    [Fact]
    public void GetSortKey_NameOrderDescending_ReturnsTheSameKeyAsAscending()
    {
        // Direction is applied by the sorting pipeline, never by negating the key. If Desc
        // ever started returning an inverted key, multi-sort would double-invert it.
        var item = NewAudio("Track Name", "0001 - Track Name");

        Assert.Equal("Track Name", new NameOrder().GetSortKey(item, null!, null, null));
        Assert.Equal("Track Name", new NameOrderDesc().GetSortKey(item, null!, null, null));
    }

    // =================================================================================
    // NameIgnoreArticlesOrder - StripLeadingArticles
    // Only "the" is in the article list (a/an and the other languages are commented out in
    // OrderUtilities.Articles), and it only counts when followed by a space.
    // =================================================================================

    [Theory]
    [InlineData("The Matrix", "Matrix")]
    [InlineData("THE MATRIX", "MATRIX")]              // case-insensitive match
    [InlineData("the matrix", "matrix")]
    [InlineData("  The Matrix", "Matrix")]            // leading whitespace is trimmed first
    [InlineData("The Matrix  ", "Matrix")]            // trailing whitespace is trimmed too
    [InlineData("The   Matrix", "Matrix")]            // remainder is TrimStart'ed
    [InlineData("A Bug's Life", "A Bug's Life")]      // "a" is NOT an article here
    [InlineData("An Ant", "An Ant")]                  // "an" is NOT an article here
    [InlineData("The", "The")]                        // whole name is the article: no space
    [InlineData("Theater", "Theater")]                // prefix match must not be enough
    [InlineData("The-Matrix", "The-Matrix")]          // separator must be a space
    [InlineData("Le Fabuleux Destin", "Le Fabuleux Destin")]  // French article: not stripped
    [InlineData("Der Untergang", "Der Untergang")]            // German article: not stripped
    [InlineData("Det Sjunde Inseglet", "Det Sjunde Inseglet")] // Swedish: not stripped
    [InlineData("", "")]
    [InlineData("   ", "   ")]                        // whitespace-only is returned untouched
    public void ComputeNameIgnoreArticlesSortValue_StripsOnlyLeadingThe(string name, string expected)
    {
        var movie = NewMovie(name);

        Assert.Equal(expected, NameIgnoreArticlesOrder.ComputeNameIgnoreArticlesSortValue(movie));
    }

    [Fact]
    public void ComputeNameIgnoreArticlesSortValue_SortNamePresent_IsUsedVerbatimWithItsArticle()
    {
        // Deliberate: a manual sort title is the user's own answer, so articles are left alone.
        var withSortName = NewMovie("The Matrix", "The Matrix");
        var withoutSortName = NewMovie("The Matrix");

        Assert.Equal("The Matrix", NameIgnoreArticlesOrder.ComputeNameIgnoreArticlesSortValue(withSortName));
        Assert.Equal("Matrix", NameIgnoreArticlesOrder.ComputeNameIgnoreArticlesSortValue(withoutSortName));
    }

    [Theory]
    [InlineData("001 - 0001 - The Pilot", "Pilot")]        // auto-generated -> strip from Name
    [InlineData("0012 - 00034 - The Pilot", "Pilot")]      // 3+ / 4+ digits
    [InlineData("01 - 0001 - x", "01 - 0001 - x")]         // 2 digits: manual
    [InlineData("001 - 001 - x", "001 - 001 - x")]         // 3 digits in group 2: manual
    [InlineData("A", "A")]                                 // manual sort title wins
    [InlineData("", "Pilot")]                              // no sort name -> strip from Name
    public void ComputeNameIgnoreArticlesSortValue_Episode_StripsFromNameOnlyForAutoGeneratedSortNames(string sortName, string expected)
    {
        var episode = NewEpisode("The Pilot", sortName);

        Assert.Equal(expected, NameIgnoreArticlesOrder.ComputeNameIgnoreArticlesSortValue(episode));
    }

    [Fact(Skip = "suspected real bug: the two episode auto-sort-name detectors disagree. "
        + "NameSortHelper uses ^\\d{3,}\\s+-\\s+\\d{4,}\\s+-\\s+ (any whitespace run) while "
        + "NameIgnoreArticlesOrder uses ^\\d{3,} - \\d{4,} -  (literal single spaces). They are "
        + "meant to detect the same thing, so the same episode is 'auto-generated' to Name "
        + "Ascending and 'manual' to Name (Ignore Articles) Ascending. Fix by widening the "
        + "NameIgnoreArticlesOrder pattern to \\s+, then un-skip.")]
    public void ComputeNameIgnoreArticlesSortValue_EpisodePattern_AgreesWithNameSortHelper()
    {
        // Written to the intended behaviour: both detectors should recognise the same
        // auto-generated sort name and fall back to the item's Name.
        var episode = NewEpisode("The Pilot", "001  -  0001  -  The Pilot");

        Assert.Equal("The Pilot", NameSortHelper.GetNameSortValue(episode));
        Assert.Equal("Pilot", NameIgnoreArticlesOrder.ComputeNameIgnoreArticlesSortValue(episode));
    }

