            NewAudio("alpha track", artists: ["Alpha Artist"]),
        };

        // The artistless item keys on "" and so leads ascending / trails descending, and the
        // comparison itself is case-insensitive ("Alpha Artist" before "beta artist").
        Assert.Equal(["no artist", "alpha track", "beta track"], NamesOf(new ArtistOrder().OrderBy(items)));
        Assert.Equal(["beta track", "alpha track", "no artist"], NamesOf(new ArtistOrderDesc().OrderBy(items)));
    }
