/// <summary>
/// Covers every name/text based sort: <see cref="NameOrder"/> (+Desc) and its
/// <c>NameSortHelper</c>, <see cref="NameIgnoreArticlesOrder"/> (+Desc),
/// <see cref="SeriesNameOrder"/> (+Desc), <see cref="SeriesNameIgnoreArticlesOrder"/> (+Desc)
/// and <see cref="ArtistOrder"/> (+Desc).
///
/// TWO PRECONDITIONS that every test in this file depends on, both properties of Jellyfin's
/// BaseItem rather than of the plugin:
///
/// 1. Reading <c>item.SortName</c> when it was never assigned throws NullReferenceException -
///    the getter falls through to CreateSortName(), which needs a running server. Every item
///    built here therefore gets an EXPLICIT SortName, and "no sort name" is modelled as the
///    empty string (the code under test only ever tests <c>string.IsNullOrEmpty(SortName)</c>,
///    so "" and null are indistinguishable to it - null is simply not reachable in a test).
/// 2. Assigning <c>Name</c> resets the cached sort name, so in every object initializer below
///    Name is assigned BEFORE SortName. Swapping those two lines reintroduces the NRE in (1).
///
/// <c>user</c>, <c>userDataManager</c> and <c>logger</c> are passed as null throughout: none of
/// these orders read them (the only use of logger is a warning on a reflection failure that
/// cannot happen for the types used here).
/// </summary>
public class NameOrderTests
{
    // ---------------------------------------------------------------------------------
    // Item builders. Id is always set: BaseItem.Id defaults to Guid.Empty, so leaving it
    // alone makes every item collide in any Id-keyed lookup.
    // ---------------------------------------------------------------------------------

    private static Movie NewMovie(string? name, string sortName = "") =>
        new() { Id = Guid.NewGuid(), Name = name!, SortName = sortName };

    private static Audio NewAudio(string? name, string sortName = "", string[]? artists = null)
    {
        var audio = new Audio { Id = Guid.NewGuid(), Name = name!, SortName = sortName };
        if (artists is not null)
        {
            audio.Artists = artists;
        }

        return audio;
    }

    private static Episode NewEpisode(string? name, string sortName = "", string? seriesName = null, Guid seriesId = default) =>
        new()
        {
            Id = Guid.NewGuid(),
            Name = name!,
            SortName = sortName,
            SeriesName = seriesName!,
            SeriesId = seriesId,
        };

    private static string[] NamesOf(IEnumerable<BaseItem> items) => items.Select(i => i.Name).ToArray();

    // =================================================================================
    // NameSortHelper - auto-generated SortName detection
    // Audio pattern:   ^\d+\s+-\s+          e.g. "0001 - Track Title"
    // Episode pattern: ^\d{3,}\s+-\s+\d{4,}\s+-\s+   e.g. "001 - 0001 - Title"
    // A match means "Jellyfin generated this, the user asked for Name, so use Name".
    // Anything else is treated as a MANUAL sort title and wins over Name.
    // =================================================================================

    [Theory]
    // Auto-generated shapes -> fall back to Name.
    [InlineData("0001 - Whatever", "Track Name")]
    [InlineData("1 - Whatever", "Track Name")]           // \d+ : a single digit is enough
    [InlineData("12   -   Whatever", "Track Name")]      // \s+ : any run of whitespace
    [InlineData("0001 -\tWhatever", "Track Name")]       // \s+ : tab counts as whitespace
    [InlineData("0001 - ", "Track Name")]                // nothing after the separator
    // Near-misses that must be respected as manual sort titles.
    [InlineData("0001- Whatever", "0001- Whatever")]     // no whitespace before the hyphen
    [InlineData("0001 -Whatever", "0001 -Whatever")]     // no whitespace after the hyphen
    [InlineData("0001 – Whatever", "0001 – Whatever")] // en dash, not a hyphen
    [InlineData("0001 -- Whatever", "0001 -- Whatever")] // double hyphen
    [InlineData(" 0001 - Whatever", " 0001 - Whatever")] // leading space: not anchored at start
    [InlineData("A 0001 - Whatever", "A 0001 - Whatever")]
    [InlineData("Manual Title", "Manual Title")]
    // Empty sort name -> Name.
    [InlineData("", "Track Name")]
    public void GetNameSortValue_Audio_FallsBackToNameOnlyForAutoGeneratedSortNames(string sortName, string expected)
    {
        var audio = NewAudio("Track Name", sortName);

        Assert.Equal(expected, NameSortHelper.GetNameSortValue(audio));
    }

    [Theory]
    // Auto-generated shapes -> fall back to Name.
    [InlineData("001 - 0001 - Whatever", "Pilot")]
    [InlineData("0012   -   00034   -   Whatever", "Pilot")] // 3+ / 4+ digits, \s+ separators
    // Near-misses that must be respected as manual sort titles.
    [InlineData("01 - 0001 - Whatever", "01 - 0001 - Whatever")]   // only 2 leading digits
    [InlineData("001 - 001 - Whatever", "001 - 001 - Whatever")]   // only 3 digits in group 2
    [InlineData("001 - 0001 -Whatever", "001 - 0001 -Whatever")]   // no space after 2nd hyphen
    [InlineData("001 - 0001", "001 - 0001")]                       // second separator missing
    [InlineData("A", "A")]                                         // the documented manual case
    [InlineData("", "Pilot")]
    public void GetNameSortValue_Episode_FallsBackToNameOnlyForAutoGeneratedSortNames(string sortName, string expected)
    {
        var episode = NewEpisode("Pilot", sortName);

        Assert.Equal(expected, NameSortHelper.GetNameSortValue(episode));
    }

    [Fact]
    public void GetNameSortValue_AutoGeneratedPatterns_AreScopedToTheirOwnItemType()
    {
        // The audio pattern is only consulted for Audio and the episode pattern only for
        // Episode, so the very same string is "auto-generated" on one type and a manual sort
        // title on another. A Movie is neither, so it always keeps its SortName.
        Assert.Equal("0001 - Whatever", NameSortHelper.GetNameSortValue(NewMovie("Movie Name", "0001 - Whatever")));
        Assert.Equal("001 - 0001 - Whatever", NameSortHelper.GetNameSortValue(NewMovie("Movie Name", "001 - 0001 - Whatever")));

        // An episode-shaped sort name on an Episode is auto-generated...
        Assert.Equal("Pilot", NameSortHelper.GetNameSortValue(NewEpisode("Pilot", "001 - 0001 - Whatever")));
        // ...but an audio-shaped one on an Episode is not: it fails the 3+/4+ digit pattern.
        Assert.Equal("0001 - Whatever", NameSortHelper.GetNameSortValue(NewEpisode("Pilot", "0001 - Whatever")));
        // The audio pattern is the looser of the two, so it also swallows episode-shaped
        // sort names when the item happens to be Audio.
        Assert.Equal("Track", NameSortHelper.GetNameSortValue(NewAudio("Track", "001 - 0001 - Whatever")));
    }

    [Fact]
    public void GetNameSortValue_NullName_ReturnsEmptyString()
    {
        Assert.Equal("", NameSortHelper.GetNameSortValue(NewAudio(null, "0001 - Gone")));
        Assert.Equal("", NameSortHelper.GetNameSortValue(NewEpisode(null, "001 - 0001 - Gone")));
        Assert.Equal("", NameSortHelper.GetNameSortValue(NewMovie(null)));
    }

    [Fact]
    public void GetNameSortValue_NullItem_ThrowsArgumentNullException()
    {
        Assert.Throws<ArgumentNullException>(() => NameSortHelper.GetNameSortValue(null!));
    }

