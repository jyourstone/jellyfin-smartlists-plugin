    [Fact]
    public void GetSortKey_SeriesNameDescending_MatchesAscending_AcrossEveryFallbackBranch()
    {
        // SeriesNameOrderDesc re-implements the whole body of SeriesNameOrder instead of
        // sharing it, so the two can silently drift apart. This walks all four branches.
        var seriesId = Guid.NewGuid();
        var cache = new RefreshQueueService.RefreshCache();
        cache.SeriesNameById[seriesId] = "The IT Crowd";
        cache.SeriesSortNameById[seriesId] = "IT Crowd, The";

        BaseItem[] samples =
        [
            NewEpisode("Cached", sortName: "", seriesId: seriesId),                       // cache hit
            NewEpisode("SortName", sortName: "Manual", seriesName: "Series"),             // item.SortName
            NewEpisode("Reflected", sortName: "", seriesName: "The Wire"),                // reflection
            NewMovie("No Series"),                                                        // empty
        ];

        var asc = new SeriesNameOrder();
        var desc = new SeriesNameOrderDesc();
        foreach (var item in samples)
        {
            Assert.Equal(
                asc.GetSortKey(item, null!, null, null, null, cache),
                desc.GetSortKey(item, null!, null, null, null, cache));
        }

        var ascIgnore = new SeriesNameIgnoreArticlesOrder();
        var descIgnore = new SeriesNameIgnoreArticlesOrderDesc();
        foreach (var item in samples)
        {
            Assert.Equal(
                ascIgnore.GetSortKey(item, null!, null, null, null, cache),
                descIgnore.GetSortKey(item, null!, null, null, null, cache));
        }
    }

    [Fact]
    public void OrderBy_SeriesName_UsesTheCacheAndReversesUnderDescending()
    {
        var alien = Guid.NewGuid();
        var bosch = Guid.NewGuid();
        var cache = new RefreshQueueService.RefreshCache();
        cache.SeriesNameById[alien] = "The Alienist";
        cache.SeriesNameById[bosch] = "Bosch";

        var items = new BaseItem[]
        {
            NewEpisode("A1", sortName: "", seriesId: alien),
            NewEpisode("B1", sortName: "", seriesId: bosch),
        };

        // "Bosch" < "The Alienist" alphabetically...
        Assert.Equal(["B1", "A1"], NamesOf(new SeriesNameOrder().OrderBy(items, null!, null, null, cache)));
        Assert.Equal(["A1", "B1"], NamesOf(new SeriesNameOrderDesc().OrderBy(items, null!, null, null, cache)));

        // ...but "Alienist" < "Bosch" once the article is stripped.
        Assert.Equal(["A1", "B1"], NamesOf(new SeriesNameIgnoreArticlesOrder().OrderBy(items, null!, null, null, cache)));
        Assert.Equal(["B1", "A1"], NamesOf(new SeriesNameIgnoreArticlesOrderDesc().OrderBy(items, null!, null, null, cache)));
    }

