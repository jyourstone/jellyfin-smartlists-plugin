    // =================================================================================
    // SeriesNameOrder vs SeriesNameIgnoreArticlesOrder
    // The pair exists so users can pick "The IT Crowd" or "IT Crowd", so their cache
    // precedence is deliberately opposite:
    //   SeriesNameOrder              : SeriesNameById  -> SeriesSortNameById -> ...
    //   SeriesNameIgnoreArticlesOrder: SeriesSortNameById -> SeriesNameById(stripped) -> ...
    // =================================================================================

    private static string SeriesKey(BaseItem item, RefreshQueueService.RefreshCache? cache) =>
        (string)new SeriesNameOrder().GetSortKey(item, null!, null, null, null, cache);

    private static string SeriesIgnoreArticlesKey(BaseItem item, RefreshQueueService.RefreshCache? cache) =>
        (string)new SeriesNameIgnoreArticlesOrder().GetSortKey(item, null!, null, null, null, cache);

    [Fact]
    public void GetSortValue_BothCacheEntriesPresent_TheTwoSeriesOrdersDeliberatelyDisagree()
    {
        var seriesId = Guid.NewGuid();
        var cache = new RefreshQueueService.RefreshCache();
        cache.SeriesNameById[seriesId] = "The IT Crowd";
        cache.SeriesSortNameById[seriesId] = "IT Crowd, The";
        var episode = NewEpisode("Yesterday's Jam", sortName: "", seriesName: "ignored", seriesId: seriesId);

        Assert.Equal("The IT Crowd", SeriesKey(episode, cache));
        Assert.Equal("IT Crowd, The", SeriesIgnoreArticlesKey(episode, cache));
    }

    [Fact]
    public void GetSortValue_OnlyCachedSeriesName_IsStrippedByTheIgnoreArticlesVariantOnly()
    {
